<#
.SYNOPSIS
  Exports everything the menu draws into assets/*.bin (compiled into kerneloscope.efi by build.rs).
  Only needed after changing the look; the committed assets/ are ready to build. Windows-only (uses Edge).
  - corner decorations / title / hint bars: rendered from HTML/CSS with headless Edge
    (the background gradient and the stars are generated by the menu at the screen's own size)
  - OS + tool icons and selection frames: rendered by tools/render-icons.ps1 -Scale $Density from art/logos
  - fonts: proportional Bahnschrift atlases drawn with System.Drawing

  All images are drawn at $Density x (2x by default) of the 2560x1600 layout size.
  Image .bin format (little endian):  "IMG1" u32 width, u32 height, then zlib( BGRA bytes, straight alpha )
  Font  .bin format:                  "FNT1" u32 cellW, u32 cellH, u32 count(95, ASCII 32..126),
                                      count x u8 advance, then zlib( alpha bytes, cellW*count x cellH strip )
.EXAMPLE
  ./tools/export-assets.ps1
#>
param(
    [string]$Accent = '#ff1f3d',
    [int]$Width = 2560,
    [int]$Height = 1600,
    [int]$Density = 2,                # assets are drawn at 2x so they stay sharp up to ~5K screens (must match ASSET_DENSITY in src/main.rs)
    [string]$Edge = 'C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe'
)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root   = Resolve-Path (Join-Path $PSScriptRoot '..')
$out    = Join-Path $root 'assets'
$work   = Join-Path $root 'build\render'
New-Item -ItemType Directory -Force $out, $work | Out-Null
Get-ChildItem $out -Filter *.bin -ErrorAction SilentlyContinue | Remove-Item

# OS logos, tool icons and selection frames, rendered at $Density x into a build folder
$themeOut = Join-Path $root 'build\icons-hires'
& (Join-Path $PSScriptRoot 'render-icons.ps1') -Scale $Density -OutRoot $themeOut | Out-Null
$themeIcons = Join-Path $themeOut 'icons\icons'

function Write-Blob([string]$path, [string]$magic, [byte[]]$header, [byte[]]$payload) {
    $ms = New-Object IO.MemoryStream
    $z = New-Object IO.Compression.ZLibStream($ms, [IO.Compression.CompressionLevel]::SmallestSize)
    $z.Write($payload, 0, $payload.Length); $z.Dispose()
    $fs = [IO.File]::Create($path)
    $fs.Write([Text.Encoding]::ASCII.GetBytes($magic), 0, 4); $fs.Write($header, 0, $header.Length)
    $c = $ms.ToArray(); $fs.Write($c, 0, $c.Length); $fs.Dispose()
}
function U32([int]$v) { [BitConverter]::GetBytes([uint32]$v) }

function Export-Png([string]$png, [string]$name) {
    $bmp = [System.Drawing.Bitmap]::new($png)
    $rect = New-Object System.Drawing.Rectangle 0, 0, $bmp.Width, $bmp.Height
    $data = $bmp.LockBits($rect, 'ReadOnly', [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)  # memory order B,G,R,A
    $bytes = New-Object byte[] ($bmp.Width * $bmp.Height * 4)
    for ($y = 0; $y -lt $bmp.Height; $y++) {
        [Runtime.InteropServices.Marshal]::Copy([IntPtr]($data.Scan0.ToInt64() + $y * $data.Stride), $bytes, $y * $bmp.Width * 4, $bmp.Width * 4)
    }
    $bmp.UnlockBits($data)
    Write-Blob (Join-Path $out "$name.bin") 'IMG1' ((U32 $bmp.Width) + (U32 $bmp.Height)) $bytes
    $bmp.Dispose()
}

function Render([string]$name, [int]$w, [int]$h, [string]$css, [string]$body) {
    $html = Join-Path $work "$name.html"; $png = Join-Path $work "$name.png"
    "<!doctype html><html><head><meta charset='utf-8'><style>html,body{margin:0;width:${w}px;height:${h}px;overflow:hidden;background:transparent}$css</style></head><body>$body</body></html>" |
        Set-Content -Encoding utf8 $html
    if (Test-Path $png) { Remove-Item $png }
    & $Edge --headless=new --disable-gpu --hide-scrollbars "--force-device-scale-factor=$Density" "--user-data-dir=$work\edge-profile" `
        --default-background-color=00000000 "--window-size=$w,$h" "--screenshot=$png" ([Uri]$html).AbsoluteUri 2>$null | Out-Null
    if (-not (Test-Path $png)) { throw "Edge failed to render $name" }
    Export-Png $png $name
}

