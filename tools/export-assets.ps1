# ---------------------------------------------------------------- proportional font atlases
function Export-Font([string]$name, [string]$family, [int]$px, [System.Drawing.FontStyle]$style) {
    $font = New-Object System.Drawing.Font $family, $px, $style, ([System.Drawing.GraphicsUnit]::Pixel)
    $fmt = [System.Drawing.StringFormat]::GenericTypographic.Clone(); $fmt.FormatFlags = $fmt.FormatFlags -bor [System.Drawing.StringFormatFlags]::MeasureTrailingSpaces
    $tmp = New-Object System.Drawing.Bitmap 8, 8; $tg = [System.Drawing.Graphics]::FromImage($tmp); $tg.TextRenderingHint = 'AntiAlias'
    # true advance = width("H" + c + "H") - width("HH"): measuring a glyph alone drops its side bearings,
    # which makes narrow characters like ( ) l i crowd their neighbours
    $pair = $tg.MeasureString('HH', $font, 4000, $fmt).Width
    $spaceW = $tg.MeasureString(' ', $font, 4000, $fmt).Width
    $adv = foreach ($c in 32..126) { [int][Math]::Round($tg.MeasureString("H$([char]$c)H", $font, 4000, $fmt).Width - $pair) }
    $tg.Dispose(); $tmp.Dispose()
    # Each cell holds one glyph with its pen origin at x = $pad (the menu draws cells at pen - pad).
    # The glyph is drawn after a space so GDI+ positions it with its real side bearing, exactly as in
    # running text; the left padding keeps glyphs with negative bearings from being clipped.
    $pad = 4 * $Density
    $cellW = ($adv | Measure-Object -Maximum).Maximum + 3 * $pad; $cellH = [int]($px * 1.35)
    $bmp = New-Object System.Drawing.Bitmap ($cellW * 95), $cellH, ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $g = [System.Drawing.Graphics]::FromImage($bmp); $g.TextRenderingHint = 'AntiAlias'; $g.Clear([System.Drawing.Color]::Transparent)
    for ($i = 0; $i -lt 95; $i++) {
        $g.SetClip((New-Object System.Drawing.RectangleF ($i * $cellW), 0, $cellW, $cellH))
        $g.DrawString(" $([char](32 + $i))", $font, [System.Drawing.Brushes]::White, [float]($i * $cellW + $pad - $spaceW), [float]($px * 0.12), $fmt)
    }
    $g.Dispose()
    $alpha = New-Object byte[] ($bmp.Width * $cellH)
    for ($y = 0; $y -lt $cellH; $y++) { for ($x = 0; $x -lt $bmp.Width; $x++) { $alpha[$y * $bmp.Width + $x] = $bmp.GetPixel($x, $y).A } }
    $bmp.Dispose()
    Write-Blob (Join-Path $out "$name.bin") 'FNT1' ((U32 $cellW) + (U32 $cellH) + (U32 95) + [byte[]]($adv | % { [byte]$_ })) $alpha
}
Export-Font 'font_label' 'Bahnschrift' (32 * $Density) ([System.Drawing.FontStyle]::Regular)
Export-Font 'font_menu' 'Bahnschrift' (36 * $Density) ([System.Drawing.FontStyle]::Regular)
Export-Font 'font_title' 'Bahnschrift' (30 * $Density) ([System.Drawing.FontStyle]::Bold)

Get-ChildItem $out | Measure-Object Length -Sum | % { "Exported $($_.Count) assets, $([Math]::Round($_.Sum/1MB,2)) MB to $out" }
