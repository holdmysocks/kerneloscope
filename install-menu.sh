#!/usr/bin/env bash
# Installs Kerneloscope on this Linux system's EFI partition and makes it the first firmware boot entry.
# Your existing boot loaders (GRUB, systemd-boot, rEFInd, Windows Boot Manager) stay installed and in the
# firmware boot list, so the firmware's own boot menu can always reach them.
#
#   sudo bash ./install-menu.sh            install / update (an existing menu.conf is kept)
#   sudo bash ./install-menu.sh --remove   remove the firmware entry and the files
#
# Uses the prebuilt  dist/kerneloscope.efi  next to this script, or a fresh build in target/ if there is one
# (build: rustup target add x86_64-unknown-uefi && cargo build --release --target x86_64-unknown-uefi).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
[[ $EUID -eq 0 ]] || { echo "Run with sudo:  sudo bash $0"; exit 1; }
command -v efibootmgr >/dev/null || { echo "efibootmgr is missing: install it with your package manager (e.g. pacman/apt/dnf install efibootmgr)"; exit 1; }

# ---- locate the EFI partition (usually mounted at /boot, /boot/efi or /efi)
ESP=""
for m in /boot/efi /efi /boot; do
  if [[ "$(findmnt -no FSTYPE "$m" 2>/dev/null)" == "vfat" ]]; then ESP="$m"; break; fi
done
[[ -n "$ESP" ]] || { echo "No FAT EFI partition mounted at /boot, /boot/efi or /efi"; exit 1; }
SRC="$(findmnt -no SOURCE "$ESP")"
DISK="/dev/$(lsblk -no PKNAME "$SRC")"
PART="$(cat "/sys/class/block/$(basename "$SRC")/partition")"
DEST="$ESP/EFI/kerneloscope"
echo "EFI partition: $SRC (disk $DISK, partition $PART) mounted at $ESP"

if [[ "${1:-}" == "--remove" ]]; then
  for n in $(efibootmgr | sed -nE 's/^Boot([0-9A-F]{4})\*? Kerneloscope.*/\1/p'); do efibootmgr -b "$n" -B >/dev/null; done
  rm -rf "$DEST"
  echo "Kerneloscope removed."
  exit 0
fi

EFI="$HERE/target/x86_64-unknown-uefi/release/kerneloscope.efi"
[[ -f "$EFI" ]] || EFI="$HERE/dist/kerneloscope.efi"
[[ -f "$EFI" ]] || { echo "Missing kerneloscope.efi (expected $HERE/dist/kerneloscope.efi) - see the top of this script"; exit 1; }
echo "Installing $EFI"
mkdir -p "$DEST"
cp "$EFI" "$DEST/kerneloscope.efi"

# ---- write menu.conf for this machine (an existing one is kept; delete it to regenerate)
if [[ ! -f "$DEST/menu.conf" ]]; then
  . /etc/os-release
  TITLE="${NAME:-Linux}"
  ICON="${ID:-linux}"
  ROOT_UUID="$(findmnt -no UUID /)"
  FSTYPE="$(findmnt -no FSTYPE /)"; [[ "$FSTYPE" == "btrfs" ]] && SUBVOL="rootflags=subvol=$(findmnt -no FSROOT / | sed 's|^/||')" || SUBVOL=""
  BASE="root=UUID=$ROOT_UUID rw $SUBVOL"

  # the boot loader this distro already uses, as the fallback way to start it
  FALLBACK=""
  for f in EFI/refind/refind_x64.efi EFI/systemd/systemd-bootx64.efi "EFI/$ID/shimx64.efi" "EFI/$ID/grubx64.efi" EFI/BOOT/BOOTX64.EFI; do
    [[ -f "$ESP/$f" ]] && { FALLBACK="/$f"; FALLBACK="${FALLBACK//\//\\}"; break; }
  done

  {
    echo "# generated by install-menu.sh on $(date -I) - edit freely (format: see menu.conf in the Kerneloscope repo)"
    echo "timeout 8"
    echo "default \"$TITLE\""
    echo
    echo "entry \"Windows\""
    echo "  icon win"
    echo "  loader \\EFI\\Microsoft\\Boot\\bootmgfw.efi"
    echo
    echo "entry \"$TITLE\""
    echo "  icon $ICON"
    # Kernels on the EFI partition (Arch-style /boot on the ESP) are started directly via the EFI stub.
    # Otherwise, and for encrypted/LVM roots (which need the distro's own unlock setup), hand over to the
    # distro's boot loader.
    ROOT_SRC="$(findmnt -no SOURCE / | sed 's/\[.*//')"
    KERNELS=()
    if [[ "$ROOT_SRC" == /dev/mapper/* || "$ROOT_SRC" == /dev/dm-* ]]; then
      echo "Note: root is on $ROOT_SRC (encrypted/LVM) - $TITLE will start through its own boot loader" >&2
    else
      KERNELS=( $(ls "$ESP"/vmlinuz-* 2>/dev/null | grep -v '\.png$' || true) )
    fi
    if (( ${#KERNELS[@]} )); then
      first=1
      for k in "${KERNELS[@]}"; do
        name="$(basename "$k")"; flavour="${name#vmlinuz-}"
        init="\\initramfs-$flavour.img"; fb="\\initramfs-$flavour-fallback.img"
        ucode=""; for u in intel-ucode amd-ucode; do [[ -f "$ESP/$u.img" ]] && ucode+="initrd=\\$u.img "; done
        if (( first )); then
          echo "  loader \\$name"
          echo "  options \"$BASE quiet splash ${ucode}initrd=$init\""
          first=0
        else
          echo "  sub \"$TITLE ($flavour)\""
          echo "    loader \\$name"
          echo "    options \"$BASE quiet splash ${ucode}initrd=$init\""
        fi
        if [[ -f "$ESP/initramfs-$flavour-fallback.img" ]]; then
          echo "  sub \"$TITLE ($flavour, fallback initramfs)\""
          echo "    loader \\$name"
          echo "    options \"$BASE ${ucode}initrd=$fb\""
        fi
      done
      echo "  sub \"$TITLE (recovery shell)\""
      echo "    options \"$BASE single ${ucode}initrd=\\initramfs-${KERNELS[0]##*vmlinuz-}.img\""
    elif [[ -n "$FALLBACK" ]]; then
      echo "  loader $FALLBACK"
    else
      echo "Could not find kernels on the EFI partition or an existing boot loader to hand over to." >&2
      echo "Edit $DEST/menu.conf and set this entry's loader by hand." >&2
      echo "  loader \\EFI\\$ID\\grubx64.efi"
    fi
    if [[ -n "$FALLBACK" && ${#KERNELS[@]} -gt 0 ]]; then
      echo "  sub \"Previous boot loader\""
      echo "    loader $FALLBACK"
      echo "    options \"\""
    fi
  } > "$DEST/menu.conf"
  echo "Wrote $DEST/menu.conf"
fi

# ---- firmware boot entry, first in the boot order
if ! efibootmgr | grep -q ' Kerneloscope'; then
  efibootmgr --create --disk "$DISK" --part "$PART" --label "Kerneloscope" --loader '\EFI\kerneloscope\kerneloscope.efi' >/dev/null
fi
NEW="$(efibootmgr | sed -nE 's/^Boot([0-9A-F]{4})\*? Kerneloscope.*/\1/p' | head -n1)"
ORDER="$(efibootmgr | sed -nE 's/^BootOrder: //p' | tr ',' '\n' | grep -v "^$NEW$" | paste -sd, -)"
efibootmgr -o "$NEW${ORDER:+,$ORDER}" >/dev/null
echo "Boot order now: $(efibootmgr | sed -nE 's/^BootOrder: //p')  (Kerneloscope = $NEW)"
echo "Done. Reboot to see the menu. Your previous boot loaders are still in the firmware's boot menu."
